#!/usr/bin/env python3
"""
run_ti_trained_controls_transfer.py

Fair control evaluation under the same protocol as the production backbone model:

    Ti-domain-only training
        -> no-retraining prediction on Al and Cu.

Two controls are evaluated.

1. temperature_only
   Quadratic temperature regression:
       dFres = a0 + a1*T + a2*T^2

2. response_only
   Temperature plus local von Mises stress statistics:
       [T, vMises_mean, vMises_std, vMises_q25,
        vMises_q50, vMises_q75, vMises_iqr]
   fitted with standardized RBF kernel ridge regression.

The target is always the gauge-fixed residual

    dFres = dFraw - C_s,

and the absolute free-energy prediction is reconstructed as

    F_pred = F0 + C_s + dFres_pred.

Protocol
--------
- Fitting uses only alpha-TiAl, beta-TiV, and Ti64 snapshots.
- Al/Cu targets are never used for fitting or hyperparameter selection.
- The Ti-domain internal result is generated by grouped out-of-fold prediction,
  using system-temperature groups.
- Al/Cu are predicted by one final model fitted to all Ti-domain snapshots.
- Prediction re-anchoring at T0 is applied using predictions only:
      dFres_pred*(T) =
          dFres_pred(T) - mean[dFres_pred(T0)]
  separately for each evaluated system.
  No external target is used for this step.

Inputs
------
table/piml_predictions_Ti.csv
table/piml_predictions_Al.csv
table/piml_predictions_Cu.csv

Outputs
-------
table/ti_trained_control_predictions.csv
table/ti_trained_control_summary_by_system_T.csv
table/ti_trained_control_summary_by_system.csv
table/ti_trained_control_summary_global.csv
table/ti_trained_control_ordering_within_system.csv
table/ti_trained_control_ordering_fixedT.csv
table/ti_trained_control_transfer_comparison.csv
table/ti_trained_control_audit.csv
"""

