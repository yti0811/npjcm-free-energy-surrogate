def summarize_within_system_ordering(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    state_means = (
        predictions.groupby(
            ["evaluation_protocol", "method", "system", "T"],
            observed=True,
            as_index=False,
        )
        .agg(
            FANC_mean=("FANC_eVatom", "mean"),
            Fpred_mean=("signed_error_absF", lambda values: np.nan),
        )
    )

    # Avoid dynamic aggregation-column naming issues.
    state_rows: List[Dict[str, object]] = []
    for (
        protocol,
        method,
        system,
        temperature,
    ), subset in predictions.groupby(
        ["evaluation_protocol", "method", "system", "T"],
        observed=True,
        sort=True,
    ):
        absolute_col = f"Fpred_{method}"
        state_rows.append({
            "evaluation_protocol": protocol,
            "method": method,
            "system": system,
            "T": int(temperature),
            "FANC_mean": subset["FANC_eVatom"].mean(),
            "Fpred_mean": subset[absolute_col].mean(),
        })

    state_means = pd.DataFrame(state_rows)

    rows: List[Dict[str, object]] = []
    for (
        protocol,
        method,
        system,
    ), subset in state_means.groupby(
        ["evaluation_protocol", "method", "system"],
        observed=True,
        sort=True,
    ):
        subset = subset.sort_values("T")
        fviol, tau, npairs = pairwise_order_metrics(
            subset["FANC_mean"],
            subset["Fpred_mean"],
        )
        rows.append({
            "evaluation_protocol": protocol,
            "method": method,
            "system": system,
            "n_temperatures": len(subset),
            "f_viol": fviol,
            "tau": tau,
            "n_pairs": npairs,
        })

    return pd.DataFrame(rows).sort_values(
        ["evaluation_protocol", "method", "system"]
    ).reset_index(drop=True)


