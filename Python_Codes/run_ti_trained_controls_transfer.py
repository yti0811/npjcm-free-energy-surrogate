def make_temperature_only_model() -> Pipeline:
    return Pipeline([
        ("poly", PolynomialFeatures(degree=2, include_bias=False)),
        ("linear", LinearRegression()),
    ])


def response_feature_columns(
    ti: pd.DataFrame,
    external: pd.DataFrame,
) -> List[str]:
    available = [
        column
        for column in RESPONSE_FEATURE_CANDIDATES
        if column in ti.columns and column in external.columns
    ]
    if not available:
        raise ValueError(
            "No common von Mises response features were found in Ti and "
            "external prediction files."
        )

    columns = ["T", *available]
    for frame_name, frame in (("Ti", ti), ("external", external)):
        for column in columns:
            frame[column] = pd.to_numeric(frame[column], errors="coerce")
        bad = frame[columns].isna().any(axis=1)
        if bad.any():
            raise ValueError(
                f"{frame_name} data contain missing response features: "
                f"{frame.loc[bad, ['system', 'T']].head(10).to_dict('records')}"
            )

    return columns


def make_response_only_model() -> Pipeline:
    return Pipeline([
        ("scaler", StandardScaler()),
        ("krr", KernelRidge(
            alpha=1.0e-2,
            kernel="rbf",
            gamma=0.2,
        )),
    ])


# ============================================================
# Fitting and prediction
# ============================================================
def grouped_oof_prediction(
    train_df: pd.DataFrame,
    feature_columns: Sequence[str],
    model: Pipeline,
) -> np.ndarray:
    x = train_df.loc[:, list(feature_columns)].to_numpy(dtype=float)
    y = train_df["dFres_eVatom"].to_numpy(dtype=float)

    groups = (
        train_df["system"].astype(str)
        + "_"
        + train_df["T"].astype(int).astype(str)
    ).to_numpy()

    n_splits = min(MAX_GROUP_FOLDS, len(np.unique(groups)))
    if n_splits < 2:
        raise ValueError("At least two system-temperature groups are required.")

    prediction = np.full(len(train_df), np.nan, dtype=float)
    splitter = GroupKFold(n_splits=n_splits)

    for fit_idx, test_idx in splitter.split(x, y, groups):
        fitted = clone(model)
        fitted.fit(x[fit_idx], y[fit_idx])
        prediction[test_idx] = fitted.predict(x[test_idx])

    if np.isnan(prediction).any():
        raise RuntimeError("Grouped OOF prediction left missing rows.")

    return prediction


def fit_full_ti_and_predict_external(
    ti: pd.DataFrame,
    external: pd.DataFrame,
    feature_columns: Sequence[str],
    model: Pipeline,
) -> Tuple[Pipeline, np.ndarray]:
    fitted = clone(model)
    fitted.fit(
        ti.loc[:, list(feature_columns)].to_numpy(dtype=float),
        ti["dFres_eVatom"].to_numpy(dtype=float),
    )

    prediction = fitted.predict(
        external.loc[:, list(feature_columns)].to_numpy(dtype=float)
    )
    return fitted, np.asarray(prediction, dtype=float)


def reanchor_prediction_by_system(
    df: pd.DataFrame,
    prediction: Sequence[float],
    t0: float = T0,
) -> np.ndarray:
    pred = np.asarray(prediction, dtype=float).copy()
    systems = df["system"].astype(str).to_numpy()
    temperatures = df["T"].to_numpy(dtype=float)

    for system in np.unique(systems):
        system_mask = systems == system
        anchor_mask = system_mask & np.isclose(temperatures, t0)

        if not anchor_mask.any():
            raise ValueError(
                f"System {system!r} has no T0={t0:g} rows for prediction re-anchoring."
            )

        pred[system_mask] -= float(np.mean(pred[anchor_mask]))

    return pred


def append_absolute_prediction(
    df: pd.DataFrame,
    method: str,
    residual_prediction: Sequence[float],
    protocol: str,
    feature_columns: Sequence[str],
) -> pd.DataFrame:
    out = df.copy()
    residual_prediction = np.asarray(residual_prediction, dtype=float)

    residual_column = f"dFpred_{method}"
    absolute_column = f"Fpred_{method}"

    out["method"] = method
    out["evaluation_protocol"] = protocol
    out["training_domain"] = "alpha-TiAl,beta-TiV,Ti64"
    out["external_targets_used_for_fit"] = False
    out["feature_columns"] = "|".join(feature_columns)
    out[residual_column] = residual_prediction
    out[absolute_column] = (
        out["F0_eVatom"].to_numpy(float)
        + out["dFraw_T0_mean"].to_numpy(float)
        + residual_prediction
    )
    out["signed_error_absF"] = (
        out[absolute_column].to_numpy(float)
        - out["FANC_eVatom"].to_numpy(float)
    )
    out["absolute_error_absF"] = np.abs(out["signed_error_absF"])
    out["signed_error_dFres"] = (
        residual_prediction
        - out["dFres_eVatom"].to_numpy(float)
    )
    out["absolute_error_dFres"] = np.abs(out["signed_error_dFres"])

    return out


