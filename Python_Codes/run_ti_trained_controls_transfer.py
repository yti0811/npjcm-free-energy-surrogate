def build_transfer_comparison(
    by_system: pd.DataFrame,
    within_system: pd.DataFrame,
) -> pd.DataFrame:
    external_metrics = by_system[
        by_system["evaluation_protocol"].eq("external_no_retraining")
    ].copy()

    ordering = within_system[
        within_system["evaluation_protocol"].eq("external_no_retraining")
    ].copy()

    keep_ordering = ordering[
        ["method", "system", "f_viol", "tau", "n_pairs"]
    ].rename(columns={
        "f_viol": "within_system_f_viol",
        "tau": "within_system_tau",
        "n_pairs": "within_system_n_pairs",
    })

    result = external_metrics.merge(
        keep_ordering,
        on=["method", "system"],
        how="left",
        validate="one_to_one",
    )

    return result.sort_values(["system", "method"]).reset_index(drop=True)


# ============================================================
# Main
# ============================================================
def main() -> None:
    ti, external = load_inputs()

    response_columns = response_feature_columns(ti, external)

    method_specs = {
        "temp_only_ti_trained": {
            "features": ["T"],
            "model": make_temperature_only_model(),
        },
        "response_only_ti_trained": {
            "features": response_columns,
            "model": make_response_only_model(),
        },
    }

    prediction_frames: List[pd.DataFrame] = []

    for method, spec in method_specs.items():
        features = list(spec["features"])
        model = spec["model"]

        # Internal Ti-domain grouped OOF evaluation.
        ti_oof = grouped_oof_prediction(
            ti,
            features,
            model,
        )
        ti_oof = reanchor_prediction_by_system(ti, ti_oof, T0)
        prediction_frames.append(
            append_absolute_prediction(
                ti,
                method,
                ti_oof,
                "Ti_grouped_OOF",
                features,
            )
        )

        # Fit all Ti data once, then transfer without retraining to Al/Cu.
        _, external_prediction = fit_full_ti_and_predict_external(
            ti,
            external,
            features,
            model,
        )
        external_prediction = reanchor_prediction_by_system(
            external,
            external_prediction,
            T0,
        )
        prediction_frames.append(
            append_absolute_prediction(
                external,
                method,
                external_prediction,
                "external_no_retraining",
                features,
            )
        )

    predictions = pd.concat(
        prediction_frames,
        ignore_index=True,
        sort=False,
    )
    predictions.to_csv(OUT_PRED, index=False)

    by_system_temperature = summarize_by_system_temperature(predictions)
    by_system = summarize_by_system(predictions)
    global_summary = summarize_global(predictions)
    within_system = summarize_within_system_ordering(predictions)
