def read_required_csv(path: Path, domain_label: str) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Missing input file: {path}\n"
            "Run run_piml_core_pipeline_backbone.py first."
        )

    frame = pd.read_csv(path)
    missing = sorted(REQUIRED_COLUMNS - set(frame.columns))
    if missing:
        raise ValueError(
            f"{path.name} is missing required columns: {missing}"
        )

    frame = frame.copy()
    frame["evaluation_domain"] = domain_label
    frame["__source_file"] = path.name

    numeric = [
        "T",
        "FANC_eVatom",
        "F0_eVatom",
        "dFraw_T0_mean",
        "dFres_eVatom",
    ]
    for column in numeric:
        frame[column] = pd.to_numeric(frame[column], errors="coerce")

    bad = frame[numeric].isna().any(axis=1)
    if bad.any():
        examples = frame.loc[
            bad,
            ["system", "T", "snap", "timestep"]
            if "snap" in frame.columns and "timestep" in frame.columns
            else ["system", "T"],
        ].head(10)
        raise ValueError(
            f"{path.name} contains invalid required numeric values.\n"
            + examples.to_string(index=False)
        )

    reconstructed = (
        frame["F0_eVatom"].to_numpy(float)
        + frame["dFraw_T0_mean"].to_numpy(float)
        + frame["dFres_eVatom"].to_numpy(float)
    )
    reference = frame["FANC_eVatom"].to_numpy(float)
    mismatch = float(np.max(np.abs(reconstructed - reference)))
    if mismatch > 5.0e-9:
        raise ValueError(
            f"{path.name} violates FANC = F0 + Cs + dFres. "
            f"Maximum mismatch={mismatch:.6e} eV/atom."
        )

    return frame.reset_index(drop=True)


def load_inputs() -> Tuple[pd.DataFrame, pd.DataFrame]:
    ti = read_required_csv(TI_FILE, "Ti_grouped_OOF")
    al = read_required_csv(AL_FILE, "external_no_retraining")
    cu = read_required_csv(CU_FILE, "external_no_retraining")

    ti_systems_present = set(ti["system"].astype(str).unique())
    missing_ti = [system for system in TI_SYSTEMS if system not in ti_systems_present]
    if missing_ti:
        raise ValueError(
            f"Ti input is missing expected systems: {missing_ti}"
        )

    external = pd.concat([al, cu], ignore_index=True, sort=False)

    key_columns = [
        column
        for column in ("system", "T", "snap", "timestep")
        if column in ti.columns and column in external.columns
    ]
    combined = pd.concat([ti, external], ignore_index=True, sort=False)
    if key_columns and combined.duplicated(key_columns).any():
        examples = combined.loc[
            combined.duplicated(key_columns, keep=False),
            key_columns,
        ].head(20)
        raise ValueError(
            "Duplicate snapshot keys detected across inputs:\n"
            + examples.to_string(index=False)
        )

    return ti, external


# ============================================================
# Metrics
# ============================================================
def safe_kendall(y_true: Sequence[float], y_pred: Sequence[float]) -> float:
    tau, _ = kendalltau(
        np.asarray(y_true, dtype=float),
        np.asarray(y_pred, dtype=float),
    )
    return np.nan if pd.isna(tau) else float(tau)


def pairwise_order_metrics(
    y_true: Sequence[float],
    y_pred: Sequence[float],
    tol: float = 1.0e-15,
) -> Tuple[float, float, int]:
    reference = np.asarray(y_true, dtype=float)
    prediction = np.asarray(y_pred, dtype=float)

    if len(reference) != len(prediction):
        raise ValueError("Reference and prediction lengths differ.")

    violations = 0
    total = 0

    for i in range(len(reference)):
        for j in range(i + 1, len(reference)):
            d_ref = reference[i] - reference[j]
            d_pred = prediction[i] - prediction[j]

            if abs(d_ref) <= tol:
                continue

            total += 1
            if abs(d_pred) <= tol or np.sign(d_ref) != np.sign(d_pred):
                violations += 1

    if total == 0:
        return np.nan, np.nan, 0

    return (
        float(violations / total),
        safe_kendall(reference, prediction),
        int(total),
    )


def regression_metrics(
    y_true: Sequence[float],
    y_pred: Sequence[float],
) -> Dict[str, float]:
    reference = np.asarray(y_true, dtype=float)
    prediction = np.asarray(y_pred, dtype=float)

    mae = float(mean_absolute_error(reference, prediction))
    rmse = float(np.sqrt(mean_squared_error(reference, prediction)))
    if len(reference) < 2 or np.isclose(np.var(reference), 0.0):
        r2 = np.nan
    else:
        r2 = float(r2_score(reference, prediction))

    return {"MAE": mae, "RMSE": rmse, "R2": r2}


