def summarize_by_system_temperature(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for (
        protocol,
        method,
        system,
        temperature,
    ), subset in predictions.groupby(
        ["evaluation_protocol", "method", "system", "T"],
        observed=True,
        sort=True,
    ):
        absolute_col = f"Fpred_{method}"
        residual_col = f"dFpred_{method}"

        abs_metrics = regression_metrics(
            subset["FANC_eVatom"],
            subset[absolute_col],
        )
        residual_metrics = regression_metrics(
            subset["dFres_eVatom"],
            subset[residual_col],
        )

        rows.append({
            "evaluation_protocol": protocol,
            "method": method,
            "system": system,
            "T": int(temperature),
            "n_snapshots": len(subset),
            "MAE_absF": abs_metrics["MAE"],
            "RMSE_absF": abs_metrics["RMSE"],
            "R2_absF": abs_metrics["R2"],
            "MAE_dFres": residual_metrics["MAE"],
            "RMSE_dFres": residual_metrics["RMSE"],
            "R2_dFres": residual_metrics["R2"],
            "FANC_mean": subset["FANC_eVatom"].mean(),
            "Fpred_mean": subset[absolute_col].mean(),
            "state_bias_absF": (
                subset[absolute_col].mean()
                - subset["FANC_eVatom"].mean()
            ),
        })

    return pd.DataFrame(rows).sort_values(
        ["evaluation_protocol", "method", "system", "T"]
    ).reset_index(drop=True)


def summarize_by_system(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []

    for (
        protocol,
        method,
        system,
    ), subset in predictions.groupby(
        ["evaluation_protocol", "method", "system"],
        observed=True,
        sort=True,
    ):
        absolute_col = f"Fpred_{method}"
        residual_col = f"dFpred_{method}"
        abs_metrics = regression_metrics(
            subset["FANC_eVatom"],
            subset[absolute_col],
        )
        residual_metrics = regression_metrics(
            subset["dFres_eVatom"],
            subset[residual_col],
        )
        fviol, tau, npairs = pairwise_order_metrics(
            subset["FANC_eVatom"],
            subset[absolute_col],
        )

        rows.append({
            "evaluation_protocol": protocol,
            "method": method,
            "system": system,
            "n_snapshots": len(subset),
            "MAE_absF": abs_metrics["MAE"],
            "RMSE_absF": abs_metrics["RMSE"],
            "R2_absF": abs_metrics["R2"],
            "MAE_dFres": residual_metrics["MAE"],
            "RMSE_dFres": residual_metrics["RMSE"],
            "R2_dFres": residual_metrics["R2"],
            "f_viol_snapshot_pairs": fviol,
            "tau_snapshot_pairs": tau,
            "n_snapshot_pairs": npairs,
        })

    return pd.DataFrame(rows).sort_values(
        ["evaluation_protocol", "method", "system"]
    ).reset_index(drop=True)


